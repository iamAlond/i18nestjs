import { parse, TYPE } from '@formatjs/icu-messageformat-parser';
import type { MessageFormatElement } from '@formatjs/icu-messageformat-parser';

/** Maps an ICU argument name to its TypeScript value type. */
export type ExtractedArgs = Record<string, string>;

/**
 * Parses an ICU MessageFormat string and returns the arguments it requires
 * mapped to TypeScript types. Returns `null` when the message cannot be parsed.
 */
export function extractArgs(message: string): ExtractedArgs | null {
	let ast: MessageFormatElement[];
	try {
		ast = parse(message);
	} catch {
		return null;
	}

	const args: ExtractedArgs = {};
	collect(ast, args);
	return args;
}

function collect(elements: MessageFormatElement[], args: ExtractedArgs): void {
	for (const element of elements) {
		switch (element.type) {
			case TYPE.literal:
			case TYPE.pound:
				break;
			case TYPE.argument:
				args[element.value] = 'string | number';
				break;
			case TYPE.number:
				args[element.value] = 'number';
				break;
			case TYPE.date:
			case TYPE.time:
				args[element.value] = 'Date | number';
				break;
			case TYPE.select:
				args[element.value] = 'string';
				for (const option of Object.values(element.options)) {
					collect(option.value, args);
				}
				break;
			case TYPE.plural:
				args[element.value] = 'number';
				for (const option of Object.values(element.options)) {
					collect(option.value, args);
				}
				break;
			case TYPE.tag:
				collect(element.children, args);
				break;
		}
	}
}

/**
 * Generates the `declare module 'i18nestjs'` augmentation for a set of
 * fallback-language messages (dot.key -> ICU message).
 */
export function generateTypesDeclaration(messages: Map<string, string>): string {
	const keys = [...messages.keys()].sort();
	const argEntries: string[] = [];

	for (const key of keys) {
		const args = extractArgs(messages.get(key)!);
		if (args && Object.keys(args).length > 0) {
			const props = Object.entries(args)
				.map(([name, type]) => `${JSON.stringify(name)}: ${type}`)
				.join('; ');
			argEntries.push(`${JSON.stringify(key)}: { ${props} }`);
		}
	}

	const keysUnion = keys.map(key => JSON.stringify(key)).join(' | ');
	const argsBody = argEntries.length > 0 ? argEntries.join(';\n\t\t') : '';

	return `/* eslint-disable */
/* prettier-ignore */
// Generated by i18nestjs — do not edit manually.
// Regenerate with: i18nestjs types
declare module 'i18nestjs' {
	interface I18nTypes {
		keys: ${keysUnion || 'never'};
		args: {
${argsBody ? `\t\t\t${argsBody.replace(/\n/g, '\n\t\t\t')}` : ''}
		};
	}
}
`;
}
